use crate::Field as F;
use crate::Ticket;
use ConnectionType::*;

#[derive(Copy, Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum ConnectionType {
    Taxi,
    Bus,
    Underground,
    Ship,
}

impl ConnectionType {
    #[inline]
    pub fn is_usable_with_ticket(self, ticket: Ticket) -> bool {
        match self {
            Self::Taxi if ticket == Ticket::Taxi => true,
            Self::Bus if ticket == Ticket::Bus => true,
            Self::Underground if ticket == Ticket::Underground => true,
            _ => false,
        }
    }
}

pub fn destinations(from: F) -> impl Iterator<Item = (ConnectionType, F)> {
    let start = CONNECTIONS.partition_point(|(a, _, _)| *a < from);

    CONNECTIONS[start..]
        .iter()
        .copied()
        .take_while(move |(field, _, _)| field == &from)
        .map(|(_, ct, to)| (ct, to))
}

#[must_use]
pub fn is_connection(from: F, with: ConnectionType, to: F) -> bool {
    CONNECTIONS.binary_search(&(from, with, to)).is_ok()
}

